/**
 ******************************************************************************
 * @file    main.c
 * @brief   Beginner OBD-II CAN example for NUCLEO-F446RE
 *
 * Hardware path:
 *   ECUsim/vehicle -> CAN -> TJA1050 -> NUCLEO-F446RE -> USART2 -> PC/Pi
 *
 * This example requests RPM, vehicle speed, and coolant temperature.
 * It is intentionally blocking/simple so the request/response flow is easy
 * to understand. Later, move reception to interrupts and add a scheduler.
 ******************************************************************************
 */

#include "main.h"
#include "can.h"
#include "gpio.h"
#include "usart.h"
#include "obd2.h"

#include <stdio.h>
#include <string.h>

/* Generated by CubeMX in a normal project. */
void SystemClock_Config(void);

/* Send a string through USART2 for easy debug output. */
static void Debug_Print(const char *text)
{
    HAL_UART_Transmit(&huart2,
                      (uint8_t *)text,
                      (uint16_t)strlen(text),
                      HAL_MAX_DELAY);
}

/* Convert an OBD status code into a readable serial message. */
static void Debug_PrintOBDStatus(const char *name, OBD2_Status status)
{
    char line[96];

    switch (status)
    {
        case OBD2_TIMEOUT:
            snprintf(line, sizeof(line), "%s request timed out\r\n", name);
            break;

        case OBD2_BAD_RESPONSE:
            snprintf(line, sizeof(line), "%s returned a bad response\r\n", name);
            break;

        default:
            snprintf(line, sizeof(line), "%s request failed\r\n", name);
            break;
    }

    Debug_Print(line);
}

int main(void)
{
    /* Initialize STM32 HAL and the millisecond tick timer. */
    HAL_Init();

    /* Keep the real CubeMX-generated clock configuration here. */
    SystemClock_Config();

    /* Initialize peripherals generated by CubeMX. */
    MX_GPIO_Init();
    MX_CAN1_Init();
    MX_USART2_UART_Init();

    Debug_Print("\r\n========================================\r\n");
    Debug_Print(" STM32 OBD-II starter\r\n");
    Debug_Print("========================================\r\n");

    /* Install the receive filter and start CAN1. */
    if (OBD2_Init() != OBD2_OK)
    {
        Debug_Print("ERROR: Could not start CAN.\r\n");
        while (1)
        {
            HAL_Delay(1000);
        }
    }

    Debug_Print("CAN started successfully.\r\n");

    /* Raw 8-byte CAN payload returned by the ECU. */
    uint8_t response[8];

    /* CAN ID of the responding ECU, commonly 0x7E8. */
    uint32_t ecu_id = 0;

    /* Buffer used to build human-readable serial messages. */
    char line[128];

    while (1)
    {
        OBD2_Status status;

        /* ------------------------- ENGINE RPM ------------------------- */
        status = OBD2_RequestMode01PID(OBD2_PID_ENGINE_RPM,
                                       response,
                                       &ecu_id,
                                       200);

        if (status == OBD2_OK)
        {
            const float rpm = OBD2_DecodeRPM(response);
            snprintf(line, sizeof(line),
                     "ECU 0x%03lX | RPM: %.1f\r\n",
                     (unsigned long)ecu_id,
                     rpm);
            Debug_Print(line);
        }
        else
        {
            Debug_PrintOBDStatus("RPM", status);
        }

        /* ------------------------ VEHICLE SPEED ---------------------- */
        status = OBD2_RequestMode01PID(OBD2_PID_VEHICLE_SPEED,
                                       response,
                                       &ecu_id,
                                       200);

        if (status == OBD2_OK)
        {
            const uint8_t speed_kph = OBD2_DecodeSpeedKPH(response);
            snprintf(line, sizeof(line),
                     "ECU 0x%03lX | Speed: %u km/h\r\n",
                     (unsigned long)ecu_id,
                     speed_kph);
            Debug_Print(line);
        }
        else
        {
            Debug_PrintOBDStatus("Speed", status);
        }

        /* ---------------------- COOLANT TEMPERATURE ------------------ */
        status = OBD2_RequestMode01PID(OBD2_PID_COOLANT_TEMP,
                                       response,
                                       &ecu_id,
                                       200);

        if (status == OBD2_OK)
        {
            const int16_t coolant_c = OBD2_DecodeCoolantC(response);
            snprintf(line, sizeof(line),
                     "ECU 0x%03lX | Coolant: %d C\r\n",
                     (unsigned long)ecu_id,
                     coolant_c);
            Debug_Print(line);
        }
        else
        {
            Debug_PrintOBDStatus("Coolant", status);
        }

        Debug_Print("----------------------------------------\r\n");

        /*
         * Slow on purpose for the first bench test. Later, replace this
         * blocking loop with a non-blocking scheduler and different rates.
         */
        HAL_Delay(1000);
    }
}

